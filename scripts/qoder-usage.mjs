#!/usr/bin/env node
// Turns .qoder-runs/ worker logs into honest numbers for docs/QODER-USAGE.md and the deck slide.
//   node scripts/qoder-usage.mjs           write docs/QODER-USAGE.md + web/src/content/qoder-usage.json
//   node scripts/qoder-usage.mjs --print   print the markdown to stdout, write nothing
// Log shapes (see scripts/qw-watch.mjs for the streaming reader this mirrors):
//   *.jsonl  one JSON per line; assistant lines carry message.content[] tool_use parts; last line type=result.
//   *.json   a single result object (older runs, no tool lines).
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export function briefOf(fileName) {
  return basename(fileName).replace(/\.(jsonl|json)$/, "").split(".")[0];
}

export function parseRun(text) {
  const out = {
    finished: false, failed: false,
    minutes: 0, turns: 0, credits: 0,
    searches: 0, fetches: 0, commands: 0, files: [],
  };
  const seen = new Set();
  for (const line of text.split("\n")) {
    if (!line.trim()) continue;
    let m;
    try { m = JSON.parse(line); } catch { continue; }
    if (m.type === "assistant") {
      for (const part of m.message?.content ?? []) {
        if (part.type !== "tool_use") continue;
        if (part.name === "Edit" || part.name === "Write") {
          const p = part.input?.file_path;
          if (typeof p === "string" && !seen.has(p)) { seen.add(p); out.files.push(p); }
        } else if (part.name === "Bash") {
          out.commands += 1;
        }
      }
    } else if (m.type === "result") {
      out.finished = true;
      out.failed = Boolean(m.is_error);
      out.minutes = Number(m.duration_ms ?? 0) / 60000;
      out.turns = Number(m.num_turns ?? 0);
      out.credits = Number(m.total_credits ?? 0);
      out.searches = Number(m.usage?.server_tool_use?.web_search_requests ?? 0);
      out.fetches = Number(m.usage?.server_tool_use?.web_fetch_requests ?? 0);
    }
  }
  return out;
}

export function aggregate(runs) {
  // runs: [{ brief, file, parse }] as returned by readRuns / the tests
  const s = {
    runs: runs.length, briefs: new Set(runs.map((r) => r.brief)).size,
    ok: 0, failed: 0, running: 0,
    credits: 0, turns: 0, minutes: 0,
    files: new Set(), commands: 0, searches: 0, fetches: 0,
  };
  for (const r of runs) {
    const p = r.parse;
    if (!p.finished) s.running += 1;
    else if (p.failed) s.failed += 1;
    else s.ok += 1;
    s.credits += p.credits;
    s.turns += p.turns;
    s.minutes += p.minutes;
    s.commands += p.commands;
    s.searches += p.searches;
    s.fetches += p.fetches;
    for (const f of p.files) s.files.add(f);
  }
  return s;
}

const m1 = (x) => x.toFixed(1);
const m2 = (x) => x.toFixed(2);

export function renderMarkdown(s, runs) {
  const lines = [];
  lines.push("# Qoder usage");
  lines.push("");
  lines.push(`Counts from worker logs in \`.qoder-runs/\`. Generated by \`scripts/qoder-usage.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
  lines.push("");
  lines.push("| Measure | Value |");
  lines.push("|---|---|");
  lines.push(`| Worker runs | ${s.runs} |`);
  lines.push(`| Distinct briefs | ${s.briefs} |`);
  lines.push(`| Finished ok | ${s.ok} |`);
  lines.push(`| Failed | ${s.failed} |`);
  lines.push(`| Still running | ${s.running} |`);
  lines.push(`| Credits used | ${m2(s.credits)} |`);
  lines.push(`| Turns | ${s.turns} |`);
  lines.push(`| Worker minutes | ${m1(s.minutes)} |`);
  lines.push(`| Files edited or created | ${s.files.size} |`);
  lines.push(`| Shell commands run | ${s.commands} |`);
  lines.push(`| Web searches | ${s.searches} |`);
  lines.push(`| Web fetches | ${s.fetches} |`);
  lines.push("");
  lines.push("## Per run");
  lines.push("");
  lines.push("| Run | Minutes | Turns | Credits | Status |");
  lines.push("|---|---|---|---|---|");
  for (const r of runs) {
    const p = r.parse;
    const status = !p.finished ? "running" : p.failed ? "failed" : "ok";
    lines.push(`| ${r.file.replace(/\.(jsonl|json)$/, "")} | ${m1(p.minutes)} | ${p.turns} | ${m2(p.credits)} | ${status} |`);
  }
  lines.push("");
  return lines.join("\n");
}

export function slideStats(s) {
  return {
    generatedAt: new Date().toISOString(),
    summary: `${s.runs} Qoder worker runs across ${s.briefs} briefs wrote ${s.files.size} files in ${m1(s.minutes / 60)} worker hours.`,
    stats: [
      { label: "Qoder worker runs", value: s.runs },
      { label: "Files written by Qoder", value: s.files.size },
      { label: "Credits used", value: Number(m2(s.credits)) },
      { label: "Worker hours", value: Number(m1(s.minutes / 60)) },
    ],
  };
}

export function readRuns(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((n) => n.endsWith(".jsonl") || n.endsWith(".json"))
    .sort()
    .map((file) => ({ brief: briefOf(file), file, parse: parseRun(readFileSync(join(dir, file), "utf8")) }));
}

function main() {
  const runs = readRuns(join(ROOT, ".qoder-runs"));
  const s = aggregate(runs);
  const md = renderMarkdown(s, runs);
  if (process.argv.includes("--print")) {
    process.stdout.write(md);
    return;
  }
  const jsonPath = join(ROOT, "web", "src", "content", "qoder-usage.json");
  mkdirSync(dirname(jsonPath), { recursive: true });
  mkdirSync(join(ROOT, "docs"), { recursive: true });
  writeFileSync(join(ROOT, "docs", "QODER-USAGE.md"), md);
  writeFileSync(jsonPath, JSON.stringify(slideStats(s), null, 2) + "\n");
  console.log(`wrote docs/QODER-USAGE.md and web/src/content/qoder-usage.json (${s.runs} runs, ${m2(s.credits)} credits)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
